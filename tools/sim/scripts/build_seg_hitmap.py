#!/usr/bin/env python3
"""Build the 7-segment click map from the tinted layer and the decimal-point ink."""

from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1] / "img/7_segment_display_layers"
OUT = Path(__file__).resolve().parents[1] / "seven_seg_hitmap.h"

# 1=A ... 7=G. Decimal point is filled in from dp.png.
COLORS = {
    (255, 0, 0): 1,
    (11, 255, 0): 2,
    (0, 41, 255): 3,
    (235, 255, 0): 4,
    (202, 146, 28): 5,
    (175, 28, 202): 6,
    (255, 255, 255): 7,
}
DP = 8


def dp_ink(px: tuple[int, int, int, int]) -> bool:
    r, g, b, a = px
    return a >= 16 and (r + g + b) >= 40


def main() -> None:
    code = Image.open(ROOT / "color_code_for_font_builder.png").convert("RGB")
    dp = Image.open(ROOT / "dp.png").convert("RGBA")
    if code.size != dp.size:
        raise SystemExit(f"color map {code.size} != dp.png {dp.size}")
    w, h = code.size
    cells: list[int] = []
    code_px = code.load()
    dp_px = dp.load()
    for y in range(h):
        for x in range(w):
            color = code_px[x, y]
            if color in COLORS:
                cells.append(COLORS[color])
            elif color == (0, 0, 0) and dp_ink(dp_px[x, y]):
                cells.append(DP)
            else:
                cells.append(0)
    lines = [
        "#ifndef SEVEN_SEG_HITMAP_H",
        "#define SEVEN_SEG_HITMAP_H",
        "",
        "#include <stdint.h>",
        "",
        "/* Generated by tools/sim/scripts/build_seg_hitmap.py. */",
        "/* 0 is empty. 1=A 2=B 3=C 4=D 5=E 6=F 7=G 8=DP. */",
        f"#define SEVEN_SEG_HIT_W {w}",
        f"#define SEVEN_SEG_HIT_H {h}",
        "",
        f"static const uint8_t seven_seg_hitmap[SEVEN_SEG_HIT_W * SEVEN_SEG_HIT_H] = {{",
    ]
    for y in range(h):
        row = cells[y * w : (y + 1) * w]
        lines.append("    " + ", ".join(str(v) for v in row) + ",")
    lines.extend(["};", "", "#endif", ""])
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
