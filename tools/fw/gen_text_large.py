#!/usr/bin/env python3
"""Regenerate text_large.c glyph tables from img/fonts/larger_5x6_font.png."""

from pathlib import Path

try:
    from PIL import Image
except ImportError as exc:
    raise SystemExit("Pillow required: pip install pillow") from exc

ROOT = Path(__file__).resolve().parents[2]
PNG = ROOT / "img/fonts/larger_5x6_font.png"
OUT = Path(__file__).resolve().parent / "text_large.c"

W, H = 5, 6
ROW0 = list("0123456789-.,:")
ROW1 = list("ABCDEFGHIJKLMNOPQRSTUVWXYZ")


def cell(px, x0, y0):
    rows = []
    for y in range(H):
        v = 0
        for x in range(W):
            r, g, b, a = px[x0 + x, y0 + y]
            if a > 128 and (r + g + b) > 30:
                v |= 1 << x
        rows.append(v)
    return rows


def emit_block(name, chars, y0, px):
    lines = [f"static const uint8_t {name}[{len(chars)}][TEXT_LARGE_H] = {{"]
    for i, c in enumerate(chars):
        rows = cell(px, i * W, y0)
        hx = ", ".join(f"0x{r:02x}" for r in rows)
        lines.append(f"    /* {c} */ {{{hx}}},")
    lines.append("};")
    return lines


def main():
    im = Image.open(PNG).convert("RGBA")
    px = im.load()
    lines = [
        '#include "text_large.h"',
        "",
        "/* Generated by tools/fw/gen_text_large.py from img/fonts/larger_5x6_font.png */",
        "",
    ]
    lines.extend(emit_block("large_row0", ROW0, 0, px))
    lines.append("")
    lines.extend(emit_block("large_letters", ROW1, 6, px))
    lines.extend(
        [
            "",
            "static const uint8_t large_blank[TEXT_LARGE_H] = "
            "{0x00, 0x00, 0x00, 0x00, 0x00, 0x00};",
            "",
            "const uint8_t *text_large_glyph(char c)",
            "{",
            "    if (c >= '0' && c <= '9')",
            "        return large_row0[c - '0'];",
            "    if (c >= 'a' && c <= 'z')",
            "        c = (char)(c - 'a' + 'A');",
            "    if (c >= 'A' && c <= 'Z')",
            "        return large_letters[c - 'A'];",
            "    if (c == '-')",
            "        return large_row0[10];",
            "    if (c == '.')",
            "        return large_row0[11];",
            "    if (c == ',')",
            "        return large_row0[12];",
            "    if (c == ':')",
            "        return large_row0[13];",
            "    if (c == ' ')",
            "        return large_blank;",
            "    return 0;",
            "}",
            "",
        ]
    )
    OUT.write_text("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
