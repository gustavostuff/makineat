#!/usr/bin/env python3
"""Emit StageMap C sources from a platform PNG.

RGB (0,0,0) empty, (255,0,0) player spawn (not solid), any other color solid.
"""

import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError as exc:
    raise SystemExit("Pillow required: pip install pillow") from exc

SPAWN_RGB = (255, 0, 0)


def is_empty(r, g, b):
    return r == 0 and g == 0 and b == 0


def is_spawn(r, g, b):
    return (r, g, b) == SPAWN_RGB


def solid_from_png(path: Path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    px = im.load()
    row_words = (w + 15) // 16
    rows = []
    spawns = []
    for y in range(h):
        words = [0] * row_words
        for x in range(w):
            r, g, b = px[x, y]
            if is_empty(r, g, b):
                continue
            if is_spawn(r, g, b):
                spawns.append((x, y))
                continue
            wi = x // 16
            bit = x % 16
            words[wi] |= 1 << bit
        rows.extend(words)
    if len(spawns) != 1:
        raise SystemExit(f"{path.name}: expected exactly one pure red spawn pixel, found {len(spawns)}")
    spawn_x, spawn_y = spawns[0]
    return w, h, row_words, rows, spawn_x, spawn_y


def emit(w, h, row_words, rows, spawn_x, spawn_y, stem: str, png_path: Path):
    sym = stem.upper().replace("-", "_")
    lines = [
        f"/* Generated by tools/fw/gen_stage.py from {png_path.name} */",
        "",
        "#include \"stage.h\"",
        "",
        f"#define {sym}_W {w}",
        f"#define {sym}_H {h}",
        f"#define {sym}_ROW_WORDS {row_words}",
        f"#define {sym}_SPAWN_X {spawn_x}",
        f"#define {sym}_SPAWN_Y {spawn_y}",
        "",
        f"static const uint16_t {stem}_rows[{h} * {sym}_ROW_WORDS] = {{",
    ]
    for y in range(h):
        chunk = rows[y * row_words : (y + 1) * row_words]
        hx = ", ".join(f"0x{v:04x}" for v in chunk)
        lines.append(f"    {hx},")
    lines.extend(
        [
            "};",
            "",
            f"const StageMap {stem} = {{",
            f"    {sym}_W,",
            f"    {sym}_H,",
            f"    {sym}_ROW_WORDS,",
            f"    {sym}_SPAWN_X,",
            f"    {sym}_SPAWN_Y,",
            f"    {stem}_rows,",
            "};",
            "",
        ]
    )
    return "\n".join(lines)


def main():
    if len(sys.argv) != 3:
        raise SystemExit("usage: gen_stage.py <image.png> <output_basename>")
    png = Path(sys.argv[1]).resolve()
    out = Path(sys.argv[2]).resolve()
    w, h, row_words, rows, spawn_x, spawn_y = solid_from_png(png)
    stem = out.name
    body = emit(w, h, row_words, rows, spawn_x, spawn_y, stem, png)
    out.with_suffix(".c").write_text(body)
    guard = f"STAGE_{stem.upper().replace('-', '_')}_H"
    header = f"""#ifndef {guard}
#define {guard}

#include "stage.h"

extern const StageMap {stem};

#endif
"""
    out.with_suffix(".h").write_text(header)
    print("wrote", out.with_suffix(".c"), "and", out.with_suffix(".h"))


if __name__ == "__main__":
    main()
